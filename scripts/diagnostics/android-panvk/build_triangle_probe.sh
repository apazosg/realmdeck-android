#!/usr/bin/env bash
set -euo pipefail

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ARTIFACT_ROOT=/home/adrian/wowforever-artifacts/arm64-prototype
ARTIFACT_PARENT="$ARTIFACT_ROOT/controls"
OUT="$ARTIFACT_PARENT/panvk-triangle-v2-sync"
NDK=/home/adrian/android-sdk/ndk/24.0.8215888
CLANG="$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin/aarch64-linux-android29-clang"
READELF="$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-readelf"
GLSLC="$NDK/shader-tools/linux-x86_64/glslc"
SPIRV_VAL="$NDK/shader-tools/linux-x86_64/spirv-val"
ICD_SOURCE="$ARTIFACT_PARENT/panvk-audit-beta17/icd/libvulkan_panfrost.so"
HEADER=/home/adrian/wowforever-artifacts/integrated-runtime/probe-build/app/src/main/cpp/vortekrenderer/include/vulkan/vulkan_core.h
HELPER_SOURCE="$ROOT/PanvkPrivateLoader.c"
HELPER_SHA256="cc8ea0c352ff582de80ef493d6060504a5bd1b11057604a1d55dd59875b3a4b7"
HEADER_SHA256="c274cdac1e77755ad2c9e12a1d4d24a91e1f72dad138bfcd8b4a54279b9c2e71"
ICD_SHA256="5d9fdb881a66ddcd62dc06d3f6d9fe9c89b6740aaa94e3d7181d1dabab8284f9"
VERT_SOURCE="$ROOT/shaders/triangle.vert"
FRAG_SOURCE="$ROOT/shaders/triangle.frag"
VERT_SPV_SHA256="660936e4339d872b8c13d5b32e11bec2fe2cf85711ff4417212fa89356ec2ad2"
FRAG_SPV_SHA256="c27f9452b2a911ea1f66aa06a4ff721b1641ac7d3b86007fb376bfedd27db7c2"
ELF="$OUT/PanvkTriangle"
READELF_OUTPUT="$OUT/PanvkTriangle.readelf.txt"
MANIFEST="$OUT/manifest.json"

# The parent is checked before any creation.  A pre-existing output is never
# reused or overwritten; this synchronization correction owns a fresh external
# directory and leaves panvk-triangle-v1 untouched.
ls -ld -- "$ARTIFACT_ROOT" "$ARTIFACT_PARENT" >/dev/null
test -d "$ARTIFACT_ROOT" && test -d "$ARTIFACT_PARENT"
test -x "$CLANG" && test -x "$READELF"
test -x "$GLSLC" && test -x "$SPIRV_VAL"
test -f "$ROOT/PanvkTriangle.c" && test -f "$ROOT/README-triangle.md"
test -f "$VERT_SOURCE" && test -f "$FRAG_SOURCE"
test -f "$HELPER_SOURCE" && test -f "$HEADER" && test -f "$ICD_SOURCE"
test "$(sha256sum "$HELPER_SOURCE" | awk '{print $1}')" = "$HELPER_SHA256"
test "$(sha256sum "$HEADER" | awk '{print $1}')" = "$HEADER_SHA256"
test ! -e "$OUT"
mkdir -- "$OUT"
BUILD_TMP=$(mktemp -d "$OUT/.build.XXXXXX")
trap 'rm -rf -- "$BUILD_TMP"' EXIT

# Shaders are compiled on the host; the device only consumes the embedded
# SPIR-V byte arrays.  Deterministic flags; outputs are pinned by SHA-256.
"$GLSLC" -fshader-stage=vertex --target-env=vulkan1.0 -O \
  -o "$BUILD_TMP/triangle.vert.spv" "$VERT_SOURCE"
"$GLSLC" -fshader-stage=fragment --target-env=vulkan1.0 -O \
  -o "$BUILD_TMP/triangle.frag.spv" "$FRAG_SOURCE"
"$SPIRV_VAL" --target-env vulkan1.0 "$BUILD_TMP/triangle.vert.spv"
"$SPIRV_VAL" --target-env vulkan1.0 "$BUILD_TMP/triangle.frag.spv"
test "$(sha256sum "$BUILD_TMP/triangle.vert.spv" | awk '{print $1}')" = "$VERT_SPV_SHA256"
test "$(sha256sum "$BUILD_TMP/triangle.frag.spv" | awk '{print $1}')" = "$FRAG_SPV_SHA256"

python3 - "$BUILD_TMP/triangle.vert.spv" "$BUILD_TMP/triangle.frag.spv" \
  "$BUILD_TMP/triangle_spirv.h" <<'PY'
import struct
import sys

vert_path, frag_path, header_path = sys.argv[1:]

def words(path):
    with open(path, "rb") as stream:
        data = stream.read()
    assert len(data) > 0 and len(data) % 4 == 0
    return struct.unpack("<%dI" % (len(data) // 4), data)

def emit(name, values, lines):
    lines.append("static const uint32_t %s[] = {" % name)
    for index in range(0, len(values), 4):
        chunk = values[index:index + 4]
        lines.append("    " + ", ".join("0x%08xU" % value for value in chunk) + ",");
    lines.append("};")

lines = [
    "/* Generated by build_triangle_probe.sh from shaders/triangle.vert and",
    " * shaders/triangle.frag.  Reproducible: fixed formatting, no timestamps.",
    " * The device never compiles GLSL; it only consumes these arrays. */",
    "#pragma once",
    "#include <stdint.h>",
    "",
]
emit("triangle_vert_spv", words(vert_path), lines)
lines.append("")
emit("triangle_frag_spv", words(frag_path), lines)
with open(header_path, "w", encoding="ascii", newline="\n") as stream:
    stream.write("\n".join(lines) + "\n")
PY

test -f "$BUILD_TMP/triangle_spirv.h"

"$CLANG" --target=aarch64-linux-android29 -std=c11 -Os \
  -Wall -Wextra -Werror -fPIE -ffunction-sections -fdata-sections \
  -I"$(dirname "$(dirname "$HEADER")")" -I"$BUILD_TMP" \
  -Wl,--build-id=none -Wl,--as-needed -Wl,--gc-sections \
  -Wl,--no-undefined -Wl,-z,relro,-z,now -pie \
  -o "$BUILD_TMP/PanvkTriangle" "$ROOT/PanvkTriangle.c" -ldl -lc
chmod 0755 "$BUILD_TMP/PanvkTriangle"
"$READELF" --file-header --program-headers --dynamic --needed-libs --dyn-syms \
  "$BUILD_TMP/PanvkTriangle" > "$BUILD_TMP/PanvkTriangle.readelf.txt"

python3 - "$BUILD_TMP/PanvkTriangle" "$BUILD_TMP/PanvkTriangle.readelf.txt" \
  "$ROOT" "$ICD_SOURCE" "$HEADER" "$HELPER_SOURCE" "$HELPER_SHA256" \
  "$READELF" "$CLANG" "$GLSLC" "$SPIRV_VAL" \
  "$BUILD_TMP/triangle.vert.spv" "$BUILD_TMP/triangle.frag.spv" \
  "$BUILD_TMP/triangle_spirv.h" "$ELF" "$READELF_OUTPUT" "$MANIFEST" <<'PY'
import hashlib
import json
import pathlib
import re
import shutil
import stat
import struct
import subprocess
import sys

(built, report_path, root, icd, header, helper, helper_sha256, readelf_tool,
 compiler, glslc, spirv_val, vert_spv, frag_spv, spirv_header, final_elf,
 final_report, manifest) = map(pathlib.Path, sys.argv[1:])

def digest(path: pathlib.Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()

def report_for(path: pathlib.Path) -> str:
    return subprocess.check_output(
        [str(readelf_tool), "--file-header", "--program-headers", "--dynamic",
         "--needed-libs", "--dyn-syms", str(path)], text=True, encoding="ascii"
    )

report = report_path.read_text(encoding="ascii")
data = built.read_bytes()
assert data[:4] == b"\x7fELF" and data[4:6] == b"\x02\x01"
assert struct.unpack_from("<H", data, 16)[0] == 3
assert struct.unpack_from("<H", data, 18)[0] == 183
assert len(data) <= 64 * 1024
assert "Type:                              DYN" in report
assert "Machine:                           AArch64" in report
assert "Requesting program interpreter: /system/bin/linker64" in report
needed = sorted(set(re.findall(r"Shared library: \[([^\]]+)\]", report)))
assert needed == ["libc.so", "libdl.so"]
assert not re.search(r"Shared library: \[(?:libvulkan|libGL|libEGL)", report)
assert not re.search(r"UND.*\b(?:vk|gl|egl)[A-Za-z0-9_]", report, re.IGNORECASE)
assert stat.S_IMODE(built.stat().st_mode) == 0o755

icd_stat = icd.lstat()
icd_report = report_for(icd)
assert stat.S_ISREG(icd_stat.st_mode) and not stat.S_ISLNK(icd_stat.st_mode)
assert "Class:                             ELF64" in icd_report
assert "Type:                              DYN" in icd_report
assert "Machine:                           AArch64" in icd_report
assert icd.stat().st_size == 31_142_504
assert stat.S_IMODE(icd_stat.st_mode) == 0o600
assert digest(icd) == "5d9fdb881a66ddcd62dc06d3f6d9fe9c89b6740aaa94e3d7181d1dabab8284f9"

for blob in (vert_spv, frag_spv):
    content = blob.read_bytes()
    assert len(content) > 0 and len(content) % 4 == 0
assert digest(vert_spv) == "660936e4339d872b8c13d5b32e11bec2fe2cf85711ff4417212fa89356ec2ad2"
assert digest(frag_spv) == "c27f9452b2a911ea1f66aa06a4ff721b1641ac7d3b86007fb376bfedd27db7c2"

source_names = ["PanvkTriangle.c", "build_triangle_probe.sh", "README-triangle.md"]
payload = {
    "schema": "wowforever.android-panvk-triangle-build/version1",
    "file": final_elf.name,
    "size": len(data),
    "sha256": digest(built),
    "mode": "0755",
    "elfType": "ET_DYN",
    "machine": "AArch64",
    "pie": True,
    "interpreter": "/system/bin/linker64",
    "neededLibraries": needed,
    "sourceSha256": {name: digest(root / name) for name in source_names},
    "sourceBytes": {name: (root / name).stat().st_size for name in source_names},
    "helperSource": {"path": str(helper), "bytes": helper.stat().st_size,
                      "sha256": str(helper_sha256)},
    "header": {"path": str(header), "bytes": header.stat().st_size,
               "sha256": digest(header)},
    "shaders": {
        "triangle.vert": {"path": str(root / "shaders/triangle.vert"),
                          "bytes": (root / "shaders/triangle.vert").stat().st_size,
                          "sha256": digest(root / "shaders/triangle.vert")},
        "triangle.frag": {"path": str(root / "shaders/triangle.frag"),
                          "bytes": (root / "shaders/triangle.frag").stat().st_size,
                          "sha256": digest(root / "shaders/triangle.frag")},
    },
    "glslc": {"path": str(glslc), "bytes": glslc.stat().st_size,
              "sha256": digest(glslc)},
    "spirvVal": {"path": str(spirv_val), "bytes": spirv_val.stat().st_size,
                 "sha256": digest(spirv_val)},
    "spirv": {
        "vert": {"file": vert_spv.name, "bytes": vert_spv.stat().st_size,
                 "sha256": digest(vert_spv)},
        "frag": {"file": frag_spv.name, "bytes": frag_spv.stat().st_size,
                 "sha256": digest(frag_spv)},
    },
    "spirvHeader": {"file": spirv_header.name, "bytes": spirv_header.stat().st_size,
                    "sha256": digest(spirv_header)},
    "ndk": "24.0.8215888",
    "target": "aarch64-linux-android29",
    "compiler": str(compiler),
    "compilerSha256": digest(compiler),
    "compilerBytes": compiler.stat().st_size,
    "compileFlags": [
        "-std=c11", "-Os", "-Wall", "-Wextra", "-Werror", "-fPIE", "-pie",
        "--build-id=none", "-Wl,--no-undefined", "-Wl,-z,relro,-z,now",
    ],
    "linkLibraries": ["c", "dl"],
    "readelf": final_report.name,
    "icdPin": {"sourcePath": str(icd), "bytes": icd.stat().st_size,
               "mode": format(stat.S_IMODE(icd_stat.st_mode), "04o"),
               "sha256": digest(icd),
               "elf": {"type": "ET_DYN", "machine": "AArch64",
                       "reportSha256": hashlib.sha256(icd_report.encode("ascii")).hexdigest()}},
}
final_elf.write_bytes(data)
shutil.copymode(built, final_elf)
final_report.write_text(report, encoding="ascii")
manifest.write_text(json.dumps(payload, sort_keys=True, indent=2) + "\n", encoding="ascii")
for blob in (vert_spv, frag_spv, spirv_header):
    shutil.copy(blob, manifest.parent / blob.name)
print(json.dumps({"file": str(final_elf), "size": len(data),
                  "sha256": payload["sha256"], "manifest": str(manifest)}, sort_keys=True))
PY

test -f "$ELF" && test -f "$READELF_OUTPUT" && test -f "$MANIFEST"
test -f "$OUT/triangle.vert.spv" && test -f "$OUT/triangle.frag.spv"
test -f "$OUT/triangle_spirv.h"
